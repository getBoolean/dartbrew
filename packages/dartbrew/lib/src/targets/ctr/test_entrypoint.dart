/// The `test_api` versions the generated entrypoint is tested against. It
/// drives `package:test_api/backend.dart`, which has no stability promise
/// before 1.0, so other versions get a warning (KTD9).
const testedTestApi = '0.7.x';

/// Whether [version] (a resolved `test_api` version) is in [testedTestApi].
bool isTestedTestApi(String version) => RegExp(r'^0\.7\.\d').hasMatch(version);

/// The resolved `test_api` version of [project], read from `pubspec.lock`,
/// or from the package directory name in `.dart_tool/package_config.json`
/// when there is no lock file. Null when neither names it.
String? resolvedTestApiVersion(String project) {
  final lock = File(p.join(project, 'pubspec.lock'));
  if (lock.existsSync()) {
    final match = RegExp(
      r'^  test_api:\n(?:    .*\n)*?    version: "([^"]+)"',
      multiLine: true,
    ).firstMatch(lock.readAsStringSync().replaceAll('\r\n', '\n'));
    if (match != null) return match.group(1);
  }
  final config = File(p.join(project, '.dart_tool', 'package_config.json'));
  if (config.existsSync()) {
    try {
      final packages =
          (jsonDecode(config.readAsStringSync()) as Map)['packages'];
      for (final package in packages as List) {
        if (package is Map && package['name'] == 'test_api') {
          final match = RegExp(
            r'test_api-(\d+\.\d+\.\d+[^/]*)/?$',
          ).firstMatch('${package['rootUri']}');
          return match?.group(1);
        }
      }
    } on Object {
      return null;
    }
  }
  return null;
}

/// Writes the entrypoint for [testFiles] (absolute paths inside [project])
/// to `.dart_tool/dartbrew/test/dartbrew_test.dart` and returns its path.
///
/// See [testEntrypointSource] for the other parameters.
File writeTestEntrypoint({
  required String project,
  required List<String> testFiles,
  List<String> names = const [],
  List<String> plainNames = const [],
  int firstId = 0,
}) {
  final file = File(
    p.join(project, '.dart_tool', 'dartbrew', 'test', 'dartbrew_test.dart'),
  );
  file.parent.createSync(recursive: true);
  file.writeAsStringSync(
    testEntrypointSource(
      imports: [
        for (final test in testFiles)
          posixRelative(test, from: file.parent.path),
      ],
      paths: [for (final test in testFiles) posixRelative(test, from: project)],
      names: names,
      plainNames: plainNames,
      firstId: firstId,
    ),
  );
  return file;
}

/// The source of a program that runs the `package:test` files at [imports]
/// (URIs relative to the program) and prints their results as test events.
///
/// Each file is imported under its own prefix and declared into its own
/// `Declarer`, so the global `test()` and `group()` find it. Tests run as
/// `LocalTest`s through `Invoker.guard`, which keeps their errors inside the
/// test. Every event is printed as one `DARTBREW_TEST <json>` line: `suite`,
/// `group`, `testStart`, `print`, `error` and `testDone` in the shape of the
/// public JSON reporter protocol, plus a `dartbrew.plan` event per suite
/// before any test runs and a final `done`. [paths] are the suite paths the
/// events report. A test runs only when its full name matches every pattern
/// in [names] and contains every string in [plainNames]. Event IDs start at
/// [firstId].
///
/// The program imports no `dart:io`, and uses only Dart 2.12 syntax, since
/// it takes the project's language version.
String testEntrypointSource({
  required List<String> imports,
  required List<String> paths,
  List<String> names = const [],
  List<String> plainNames = const [],
  int firstId = 0,
}) {
  String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
  String list(Iterable<String> values) =>
      values.isEmpty ? '' : '\n${values.map((v) => '  $v,\n').join()}';
  return '''
// Generated by `dartbrew test`. Do not edit.
// ignore_for_file: directives_ordering, implementation_imports, depend_on_referenced_packages

import 'dart:async';
import 'dart:convert';

import 'package:test_api/backend.dart';
import 'package:test_api/hooks.dart' show TestFailure;
${[for (var i = 0; i < imports.length; i++) "import ${literal(imports[i])} as t$i;"].join('\n')}

const List<String> _paths = <String>[${list(paths.map(literal))}];
final List<Function> _mains = <Function>[${list([for (var i = 0; i < imports.length; i++) 't$i.main'])}];
final List<RegExp> _names = <RegExp>[${list(names.map((n) => 'RegExp(${literal(n)})'))}];
const List<String> _plainNames = <String>[${list(plainNames.map(literal))}];

int _nextId = $firstId;
final Stopwatch _clock = Stopwatch()..start();

void _emit(String type, Map<String, Object?> fields) {
  fields['type'] = type;
  fields['time'] = _clock.elapsedMilliseconds;
  Zone.root.print(${literal(testEventMarker)} + jsonEncode(fields));
}

/// Formats [trace] without letting a formatting failure end the run.
String _trace(StackTrace trace) {
  try {
    return trace.toString();
  } catch (error) {
    return '(stack trace unavailable: ' + error.toString() + ')';
  }
}

bool _selected(Test test) =>
    _names.every((name) => name.hasMatch(test.name)) &&
    _plainNames.every((name) => test.name.contains(name));

Map<String, Object?> _metadata(Metadata metadata) =>
    <String, Object?>{'skip': metadata.skip, 'skipReason': metadata.skipReason};

Map<String, Object?> _location(TestLocation? location) => <String, Object?>{
      'line': location?.line,
      'column': location?.column,
      'url': location?.uri.toString(),
    };

class _Suite {
  final int id;
  final Suite suite;
  final Map<Group, int> groupIds = <Group, int>{};
  _Suite(this.id, this.suite);
}

void _loadError(int suiteId, String path, Object error, StackTrace stack) {
  final id = _nextId++;
  _emit('testStart', <String, Object?>{
    'test': <String, Object?>{
      'id': id,
      'name': 'loading ' + path,
      'suiteID': suiteId,
      'groupIDs': <int>[],
      'metadata': <String, Object?>{'skip': false, 'skipReason': null},
      'line': null,
      'column': null,
      'url': null,
    },
  });
  _emit('error', <String, Object?>{
    'testID': id,
    'error': 'Failed to load "' + path + '": ' + error.toString(),
    'stackTrace': _trace(stack),
    'isFailure': false,
  });
  _emit('testDone', <String, Object?>{
    'testID': id,
    'result': 'error',
    'hidden': false,
    'skipped': false,
  });
}

List<String> _planned(Group group) {
  final names = <String>[];
  if (group.metadata.skip) return names;
  for (final entry in group.entries) {
    if (entry is Group) {
      names.addAll(_planned(entry));
    } else if (entry is Test && !entry.metadata.skip) {
      names.add(entry.name);
    }
  }
  return names;
}

List<int> _groupIds(_Suite suite, List<Group> groups) {
  final ids = <int>[];
  int? parent;
  for (final group in groups) {
    var id = suite.groupIds[group];
    if (id == null) {
      id = _nextId++;
      suite.groupIds[group] = id;
      _emit('group', <String, Object?>{
        'group': <String, Object?>{
          'id': id,
          'suiteID': suite.id,
          'parentID': parent,
          'name': group.name,
          'metadata': _metadata(group.metadata),
          'testCount': group.testCount,
          ..._location(group.location),
        },
      });
    }
    ids.add(id);
    parent = id;
  }
  return ids;
}

/// Runs [test] and returns whether it passed.
Future<bool> _run(_Suite suite, Test test, List<Group> groups,
    {bool hidden = false}) async {
  final id = _nextId++;
  _emit('testStart', <String, Object?>{
    'test': <String, Object?>{
      'id': id,
      'name': test.name,
      'suiteID': suite.id,
      'groupIDs': _groupIds(suite, groups),
      'metadata': _metadata(test.metadata),
      ..._location(test.location),
    },
  });
  if (test.metadata.skip) {
    final reason = test.metadata.skipReason;
    if (reason != null) {
      _emit('print', <String, Object?>{
        'testID': id,
        'messageType': 'skip',
        'message': 'Skip: ' + reason,
      });
    }
    _emit('testDone', <String, Object?>{
      'testID': id,
      'result': 'success',
      'hidden': false,
      'skipped': true,
    });
    return true;
  }
  final live = test.load(suite.suite, groups: groups);
  final subscriptions = <StreamSubscription<Object?>>[
    live.onMessage.listen((message) {
      _emit('print', <String, Object?>{
        'testID': id,
        'messageType': message.type.name,
        'message': message.text,
      });
    }),
    live.onError.listen((error) {
      _emit('error', <String, Object?>{
        'testID': id,
        'error': error.error.toString(),
        'stackTrace': _trace(error.stackTrace),
        'isFailure': error.error is TestFailure,
      });
    }),
  ];
  try {
    await Invoker.guard(live.run);
  } catch (error, stack) {
    _emit('error', <String, Object?>{
      'testID': id,
      'error': error.toString(),
      'stackTrace': _trace(stack),
      'isFailure': false,
    });
  }
  for (final subscription in subscriptions) {
    await subscription.cancel();
  }
  // Result is not exported by package:test_api/backend.dart; use its name.
  final result = live.state.result.name;
  final passed = result == 'success' || result == 'skipped';
  _emit('testDone', <String, Object?>{
    'testID': id,
    'result': result == 'skipped' ? 'success' : result,
    'hidden': hidden && passed,
    'skipped': result == 'skipped',
  });
  return passed;
}

Future<void> _runGroup(_Suite suite, Group group, List<Group> parents) async {
  final groups = <Group>[...parents, group];
  if (group.metadata.skip) {
    for (final entry in group.entries) {
      if (entry is Group) {
        await _runGroup(suite, entry, groups);
      } else if (entry is Test) {
        await _run(suite, entry, groups);
      }
    }
    return;
  }
  final setUpAll = group.setUpAll;
  if (setUpAll != null && !await _run(suite, setUpAll, groups, hidden: true)) {
    return;
  }
  for (final entry in group.entries) {
    if (entry is Group) {
      await _runGroup(suite, entry, groups);
    } else if (entry is Test) {
      await _run(suite, entry, groups);
    }
  }
  final tearDownAll = group.tearDownAll;
  if (tearDownAll != null) await _run(suite, tearDownAll, groups, hidden: true);
}

Future<void> main() async {
  final platform = SuitePlatform(Runtime.vm);
  final suites = <_Suite>[];
  for (var i = 0; i < _paths.length; i++) {
    final id = _nextId++;
    _emit('suite', <String, Object?>{
      'suite': <String, Object?>{'id': id, 'platform': 'vm', 'path': _paths[i]},
    });
    final body = _mains[i];
    if (body is! Function()) {
      _loadError(id, _paths[i], 'Top-level main() function takes arguments.',
          StackTrace.current);
      continue;
    }
    final declarer = Declarer();
    try {
      await runZoned(() => declarer.declare(() async {
            await (body as dynamic)();
          }), zoneValues: <Symbol, Object?>{#test.declarer: declarer});
      final suite = Suite(declarer.build(), platform, path: _paths[i])
          .filter(_selected);
      suites.add(_Suite(id, suite));
    } catch (error, stack) {
      _loadError(id, _paths[i], error, stack);
    }
  }
  for (final suite in suites) {
    _emit(${literal(planEventType)}, <String, Object?>{
      'suiteID': suite.id,
      'tests': _planned(suite.suite.group),
    });
  }
  for (final suite in suites) {
    await _runGroup(suite, suite.suite.group, <Group>[]);
  }
  _emit('done', <String, Object?>{});
}
''';
}
